// Build-time parser generator (ported from anthiel).
//
// Reads a definition file describing "key: value" style game files (region
// properties.txt, room _settings.txt, ...) and emits a header with one
// specialised parse_<object>() function per definition. All key dispatch is
// resolved into straight-line code at build time, so the runtime parsers do no
// table building, reflection or allocation beyond the values themselves.
//
// Definition format:
//
//   object_name
//       <Key> <dest> <type> <default>
//       2 <Key word1> <word2> <dest> <type> <default>        (two word keys)
//       3 <Key w1> <w2> <w3> <dest> <type> <default>         (three word keys)
//
// dest is one of:
//   member     cobj.key = parse_<type>(value)            ("Key: value")
//   member_fn  cobj.key(parse_<type>(value), err, ctx)
//   defer      cobj.key = parse_<type>(gen, err, it)      (lists, colours...)
//   defer_fn   cobj.key(parse_<type>(gen, err, it), err, ctx)
//   skip       known key whose value is not consumed (yet); silently skipped
//
// Lines starting with '//' or '#' are comments.

#include <cctype>
#include <cstdio>
#include <cstdlib>
#include <fstream>
#include <iterator>
#include <sstream>
#include <string>
#include <string_view>
#include <vector>

struct parser_member {
    std::string name;
    std::string dest;
    std::string type;
    std::string default_;
};
struct parser_object {
    std::string name;
    std::vector<parser_member> members;
};

static std::vector<std::string> split_ws(std::string const& input) {
    std::istringstream buffer(input);
    return std::vector<std::string>((std::istream_iterator<std::string>(buffer)), std::istream_iterator<std::string>());
}

// "batDepleteCyclesMin" -> "bat_deplete_cycles_min", "Broken Shelters" -> "broken_shelters"
static std::string cppify_name(std::string const& s) {
    std::string ns;
    for (size_t i = 0; i < s.size(); ++i) {
        unsigned char const c = static_cast<unsigned char>(s[i]);
        if (c == ' ') {
            // skip
        } else if (i + 1 < s.size() && c == '_' && isupper(static_cast<unsigned char>(s[i + 1]))) {
            ns += '_';
            ns += char(tolower(static_cast<unsigned char>(s[i + 1])));
            ++i;
        } else if (i > 0 && (isupper(c) || isdigit(c))) {
            ns += '_';
            ns += char(tolower(c));
        } else {
            ns += char(tolower(c));
        }
    }
    if (ns == "template")
        return ns + '_';
    return ns;
}

static bool parse_defs(char const* filename, std::vector<parser_object>& objs) {
    std::ifstream in(filename);
    if (!in)
        return false;
    std::string line;
    unsigned lineno = 0;
    while (std::getline(in, line)) {
        ++lineno;
        while (!line.empty() && (line.back() == '\r' || line.back() == '\n'))
            line.pop_back();
        if (line.starts_with("//") || line.starts_with('#'))
            continue;
        auto const tokens = split_ws(line);
        if (tokens.empty())
            continue;
        if (line[0] != ' ' && line[0] != '\t') {
            objs.push_back(parser_object{.name = tokens[0], .members = {}});
            continue;
        }
        if (objs.empty()) {
            std::fprintf(stderr, "%s:%u: member outside of object\n", filename, lineno);
            return false;
        }
        size_t words = 1;
        size_t first = 0;
        if (tokens[0] == "2" || tokens[0] == "3") {
            words = size_t(tokens[0][0] - '0');
            first = 1;
        }
        if (tokens.size() < first + words + 3) {
            std::fprintf(stderr, "%s:%u: expected <key> <dest> <type> <default>\n", filename, lineno);
            return false;
        }
        std::string name = tokens[first];
        for (size_t i = 1; i < words; ++i)
            name += ' ' + tokens[first + i];
        objs.back().members.push_back(parser_member{
            .name = name,
            .dest = tokens[first + words],
            .type = tokens[first + words + 1],
            .default_ = tokens[first + words + 2],
        });
    }
    return true;
}

static std::string generate(std::vector<parser_object> const& objs) {
    std::string out =
        "// Generated by ParserGenerator, do not edit\n"
        "#pragma once\n"
        "#include \"parsers.hpp\"\n"
        "namespace parsers {\n";
    for (auto const& o : objs)
        out += "template<typename C> " + o.name + " parse_" + o.name + "(token_generator& gen, C&& ctx, error_handler& err);\n";

    for (auto const& o : objs) {
        out += "template<typename C> " + o.name + " parse_" + o.name + "(token_generator& gen, C&& ctx, error_handler& err) {\n";
        out += "  " + o.name + " cobj;\n";
        out += "  auto it = gen.cur_tok;\n";
        out += "  auto const end = gen.tokens.cend();\n";
        out += "  while (it != end) {\n";
        out += "    if (it->type == token::type::newline) { ++it; continue; }\n";
        out += "    err.line = it->line;\n";
        out += "    if (it + 1 < end && it[0].type == token::type::identifier && it[1].type == token::type::semicolon) {\n";
        out += "      auto const key = it[0].to_string_view(gen);\n";
        out += "      bool const has_value = it + 2 < end && it[2].type == token::type::identifier;\n";
        out += "      if (false) {\n      }";
        for (auto const& m : o.members) {
            auto const field = cppify_name(m.name);
            out += " else if (key == \"" + m.name + "\") {\n";
            if (m.dest == "member") {
                out += "        if (has_value) { cobj." + field + " = parse_" + m.type + "(it[2].to_string_view(gen), err); it += 3; } else { it += 2; }\n";
            } else if (m.dest == "member_fn") {
                out += "        if (has_value) { cobj." + field + "(parse_" + m.type + "(it[2].to_string_view(gen), err), err, ctx); it += 3; } else { it += 2; }\n";
            } else if (m.dest == "defer") {
                out += "        it += 2;\n";
                out += "        cobj." + field + " = parse_" + m.type + "(gen, err, it);\n";
            } else if (m.dest == "defer_fn") {
                out += "        it += 2;\n";
                out += "        cobj." + field + "(parse_" + m.type + "(gen, err, it), err, ctx);\n";
            } else if (m.dest == "skip") {
                out += "        it += 2;\n";
                out += "        while (it != end && it->type != token::type::newline) ++it;\n";
            } else {
                std::fprintf(stderr, "unknown destination '%s' for '%s'\n", m.dest.c_str(), m.name.c_str());
                std::exit(EXIT_FAILURE);
            }
            out += "      }";
        }
        out += " else {\n";
        out += "        err.add_warning(\"unhandled key '\" + std::string{key} + \"'\");\n";
        out += "        it += 2;\n";
        out += "        while (it != end && it->type != token::type::newline) ++it;\n";
        out += "      }\n";
        out += "    } else {\n";
        out += "      err.add_warning(\"unexpected token '\" + std::string{it->to_string_view(gen)} + \"'\");\n";
        out += "      while (it != end && it->type != token::type::newline) ++it;\n";
        out += "    }\n";
        out += "  }\n";
        out += "  gen.cur_tok = it;\n";
        out += "  cobj.finish();\n";
        out += "  return cobj;\n";
        out += "}\n";
    }
    out += "}\n";
    return out;
}

int main(int argc, char* argv[]) {
    if (argc < 3) {
        std::fprintf(stderr, "usage: %s <defs.txt> <output.hpp>\n", argv[0]);
        return EXIT_FAILURE;
    }
    std::vector<parser_object> objs;
    if (!parse_defs(argv[1], objs)) {
        std::fprintf(stderr, "can't read definitions from '%s'\n", argv[1]);
        return EXIT_FAILURE;
    }
    auto const out = generate(objs);
    // only touch the output when it changes, avoids needless rebuilds
    {
        std::ifstream prev(argv[2], std::ios::binary);
        if (prev) {
            std::string const old((std::istreambuf_iterator<char>(prev)), std::istreambuf_iterator<char>());
            if (old == out)
                return EXIT_SUCCESS;
        }
    }
    std::ofstream output(argv[2], std::ios::binary | std::ios::trunc);
    if (!output)
        return EXIT_FAILURE;
    output << out;
    return output ? EXIT_SUCCESS : EXIT_FAILURE;
}
