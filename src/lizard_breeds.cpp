    char const* to_string(breed b) noexcept {
        return uint32_t(b) < breed_count ? names[uint32_t(b)] : "?";
    }

    bool parse_breed(std::string_view name, breed& out) noexcept {
        for (uint32_t i = 0; i < breed_count; ++i)
            if (name == names[i]) {
                out = breed(i);
                return true;
            }
        if (name == "spit") {
            out = breed::caramel;
            return true;
        }
        return false;
    }
