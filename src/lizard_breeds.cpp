        // a TileTypeResistance; `sand` is the Watcher's Sand accessibility,
        // which only makes a burrower here
        enum class tile : uint8_t { floor, corridor, climb, wall, ceiling, sand };
        struct resistance {
            tile accessibility;
            float cost;
        };

        // the CreatureTemplate constructor over the LizardTemplate ancestor
        // (Floor and Corridor at 1): the breed's resistances replace the
        // ancestor's, and every accessibility up to the highest allowed one
        // is allowed at no more than its cost (maxAccessibleTerrain)
        void resist(breed_params& p, std::initializer_list<resistance> list) {
            float cost[5] = {1.f, 1.f, 0.f, 0.f, 0.f};
            int32_t max = 1;
            for (auto const& r : list) {
                if (r.accessibility == tile::sand) {
                    p.burrower = true;
                    continue;
                }
                cost[uint32_t(r.accessibility)] = r.cost;
                max = std::max(max, int32_t(r.accessibility));
            }
            for (int32_t m = 0; m <= max; ++m)
                if (cost[m] == 0.f || cost[m] > cost[max])
                    cost[m] = cost[max];
            for (int32_t m = 0; m < 5; ++m)
                p.movement.resistance[m] = uint8_t(std::lround(cost[m] * 10.f));
        }

